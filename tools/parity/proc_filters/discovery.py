"""Public parameter semantics of the starter-asset filters (`phase3.2_proc-filter-families` 2.1).

`python -m tools.parity.recorder.filter_survey` describes every starter-asset filter through the
documented `Property` API into a private file. This module publishes from it, for the filters the
task names, only what `05-procedural-content.md` §3 names as public parameter semantics: per
parameter its name, label, widget type, default value, range, enum labels and values, and
visibility; per filter its resource URL and the counts of presets, image inputs and outputs
(`tools.parity.proc_generators.discovery`'s rules). Descriptions and status tips (Adobe's prose)
are not copied. The survey's SHA-256 and Painter build are the provenance.

    python -m tools.parity.proc_filters.discovery <private survey.json>
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from tools.parity.proc_generators.discovery import cell, generator
from tools.parity.schemas import REPO_ROOT

SCHEMA = "uzpainter/proc-filter-parameters/1"
OUTPUT = REPO_ROOT / "docs" / "analysis" / "proc-filter-families" / "01-parameter-discovery.md"
# UzPainter family id -> the filter's GUI name in Painter (05 §3 compatibility alias).
FAMILIES: dict[str, str] = {
    "sharpen": "Sharpen",
    "grayscale": "Grayscale Conversion",
    "blur": "Blur",
}


def publish(survey_bytes: bytes, families: Mapping[str, str] = FAMILIES) -> dict[str, Any]:
    survey = json.loads(survey_bytes)
    by_name: dict[str, list[Mapping[str, Any]]] = {}
    for row in survey["rows"]:
        by_name.setdefault(row["gui_name"], []).append(row)
    filters: dict[str, Any] = {}
    for family, name in families.items():
        rows = by_name.get(name, [])
        if len(rows) != 1:
            raise ValueError(f"{family}: {len(rows)} surveyed filters named {name!r}")
        filters[family] = {"painter_name": name, **generator(rows[0])}
    return {
        "schema": SCHEMA,
        "task": "phase3.2_proc-filter-families",
        "provenance": {
            "interface": "substance_painter_documented_python_api (properties.Property getters)",
            "survey_sha256": hashlib.sha256(survey_bytes).hexdigest(),
            "survey_schema": survey["schema"],
            "query": survey["query"],
            "painter_build": survey["painter_build"],
            "surveyed_filters": len(survey["rows"]),
        },
        "filters": filters,
    }


def markdown(document: Mapping[str, Any]) -> str:
    provenance = document["provenance"]
    build = provenance["painter_build"]["build_id"]
    lines = [
        "# Filter parameters (phase3.2_proc-filter-families item 2.1)",
        "",
        "Discovered through the documented `properties.Property` getters (approved source "
        "A-PYDOC) by `python -m tools.parity.recorder.filter_survey` on Painter "
        f"`{build}`, documented search `{provenance['query']}` "
        f"({provenance['surveyed_filters']} filters described). The survey file is private (it "
        f"stays in the owner's oracle work root); its SHA-256 is `{provenance['survey_sha256']}`. "
        "Generated by `python -m tools.parity.proc_filters.discovery`; do not edit by hand.",
        "",
        "Published here, as `05-procedural-content.md` §3 allows, for the filters this task names: "
        "parameter names, labels, widget types, default values, ranges (`min`/`max`), enum labels "
        "and values, visibility, the resource URL and the counts of presets, image inputs and "
        "outputs. No description text, no preset content, no pixel. The Levels filter is the "
        "native levels effect (`LevelsEffectNode`), not a substance, so it has no `Property` "
        "list; its fields are the documented `LevelsEffectParams`.",
        "",
        "| Family | Painter filter | Resource | Presets | Image inputs | Outputs |",
        "|---|---|---|---|---|---|",
    ]
    for family, entry in document["filters"].items():
        lines.append(
            f"| `{family}` | {entry['painter_name']} | `{entry['resource_url']}` | "
            f"{cell(entry.get('presets'))} | {cell(entry.get('image_inputs'))} | "
            f"{cell(entry.get('image_outputs'))} |"
        )
    for family, entry in document["filters"].items():
        lines += [
            "",
            f"## {entry['painter_name']} (`{family}`)",
            "",
            "| Parameter | Label | Widget | Default | Min | Max | Enum | Visible |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for name, item in entry.get("parameters", {}).items():
            lines.append(
                f"| `{name}` | {cell(item.get('label'))} | {cell(item.get('widget_type'))} | "
                f"{cell(item.get('default'))} | {cell(item.get('min'))} | "
                f"{cell(item.get('max'))} | {cell(item.get('enum'))} | "
                f"{cell(item.get('visible'))} |"
            )
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tools.parity.proc_filters.discovery")
    parser.add_argument("survey", type=Path, help="the private filter survey")
    parser.add_argument("--out", type=Path, default=OUTPUT)
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)
    document = publish(args.survey.read_bytes())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(markdown(document), encoding="utf-8", newline="\n")
    print(args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
