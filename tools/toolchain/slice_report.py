"""Hardware-slice run report of `phase0.6_toolchain-hardware-slice` (item 2.10).

    python -m tools.toolchain.slice_report --work <scratch dir> [--out <report.md>]

Run on the owner's machine (decision 028: GPU checks run locally and their report is the
evidence). Builds `zig build painter` into `<work>/dist`, then records in one Markdown report:

- `UzPainter.exe selftest` on the GPU (every stage, adapter, driver, OS build, Zig, DXC);
- the failure path with `D3D12\\D3D12Core.dll` removed from a copy of the folder;
- the link map inspection (`tools.toolchain.link_map`);
- the DLL import closure against the allowlist and its clean-machine readiness
  (`tools.toolchain.dll_closure`);
- a start of a copy of the folder with the environment reduced to the Windows folders.

Every scratch file (build, runs, map, PNG, JSON) stays under `<work>`; only the Markdown report
is written to `--out` (default `parity/reports/phase0/toolchain-hardware-slice.md`). Exit code 0
when the hardware slice passed, 1 otherwise.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from tools.toolchain.dll_closure import ClosureReport, check_folder, is_system
from tools.toolchain.link_map import CORE_ARCHIVE, LIBCXX_ARCHIVES, LinkMapReport, build_and_map

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / "parity" / "reports" / "phase0" / "toolchain-hardware-slice.md"


def run_selftest(
    exe: Path, out_dir: Path, *args: str, env: dict[str, str] | None = None
) -> tuple[int, dict[str, Any]]:
    environment = dict(os.environ if env is None else env)
    environment.pop("UZP_NO_GPU", None)
    proc = subprocess.run(
        [str(exe), "selftest", "--out-dir", str(out_dir), *args],
        capture_output=True,
        text=True,
        timeout=600,
        env=environment,
        check=False,
    )
    report = json.loads((out_dir / "selftest-report.json").read_text(encoding="utf-8"))
    return proc.returncode, report


def reduced_environment(work: Path) -> dict[str, str]:
    """Only the Windows folders: no SDK, Vulkan SDK, Python or Zig on PATH."""
    root = os.environ.get("SYSTEMROOT", r"C:\Windows")
    return {
        "SYSTEMROOT": root,
        "WINDIR": root,
        "SYSTEMDRIVE": os.environ.get("SYSTEMDRIVE", "C:"),
        "TEMP": str(work),
        "TMP": str(work),
        "PATH": f"{root}\\System32;{root}",
    }


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _stage_rows(report: dict[str, Any]) -> list[str]:
    rows = ["| Stage | Mandatory | Result | Time | Reason / facts |", "|---|---|---|---|---|"]
    for stage in report["stages"]:
        facts = stage["reason"] or ", ".join(
            f"{k} {v}" for k, v in stage["details"].items() if k not in ("file", "embree4")
        )
        rows.append(
            f"| `{stage['name']}` | {'yes' if stage['mandatory'] else 'no'} | "
            f"{stage['status']} | {stage['duration_ms']:.0f} ms | {_cell(facts)} |"
        )
    return rows


def render(
    work: Path,
    zig_version: str,
    gpu: tuple[int, dict[str, Any]],
    failure: tuple[int, dict[str, Any]],
    reduced: tuple[int, dict[str, Any]],
    link: LinkMapReport,
    closure: ClosureReport,
) -> str:
    code, report = gpu
    env = report["environment"]
    stages = {s["name"]: s for s in report["stages"]}
    device = stages["dx12-device"]["details"]
    shader = stages["shader-compile"]["details"]
    embree = stages["embree"]["details"]
    png = stages["png16"]["details"]
    build = int(env["os_build"].split(".")[2])
    windows = "Windows 11" if build >= 22000 else "Windows 10"
    lines = [
        "# Toolchain hardware slice — owner's machine run",
        "",
        "Task `phase0.6_toolchain-hardware-slice` (P0-TOOLCHAIN, `docs/dag.md`), check of "
        "`docs/architecture/13-engine-integration.md` §4.2 and §5. Decision 028: GPU checks run "
        "locally; this report is the evidence. Generated by "
        "`python -m tools.toolchain.slice_report` on "
        f"{datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}.",
        "",
        f"**Result: DX12 hardware slice {report['hardware_slice']}** "
        f"(`selftest` exit code {code}, every mandatory stage "
        f"{'passed' if report['result'] == 'passed' else 'did not pass'}).",
        "",
        "## Machine and toolchain",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| OS build | {env['os_build']} ({windows} {env['os_display_version']}; the registry "
        f'product name reads "{env["os_product"]}") |',
        f"| CPU | {env['cpu']} |",
        f"| GPU adapter | {device['adapter']} (vendor {device['vendor_id']}, device "
        f"{device['device_id']}, {device['dedicated_video_memory_mb']} MB) |",
        f"| Driver (user-mode driver version) | {device['driver_version']} |",
        f"| Feature level / highest shader model | {device['feature_level']} / "
        f"{device['shader_model']} |",
        f"| Agility SDK | `D3D12_SDK_VERSION` {device['agility_sdk_version']}, runtime "
        f"`D3D12\\D3D12Core.dll` file version {device['agility_runtime_file_version']} |",
        f"| Zig | {zig_version} (pinned 0.15.2; the executable reports {env['zig']}, "
        f"{env['build_mode']} build) |",
        f"| DXC | {shader['dxc_version']} (`dxcompiler.dll` file version "
        f"{shader['dxcompiler_file_version']}); `dxil.dll` loaded during the compile: "
        f"{shader['dxil_dll_loaded']} |",
        f"| Embree | {embree['embree_version']}, {embree['tasking_system']} tasking |",
        f"| spng | {png['spng_version']} (zlib 1.3.2) |",
        "",
        "## Stages",
        "",
        *_stage_rows(report),
        "",
        "The 16-bit pattern is 100 x 64 texels of an R16_FLOAT texture written by the DXIL "
        "kernel; it is read back through a readback buffer with a 256-byte row pitch, written "
        "as a 16-bit grayscale PNG and decoded back. `tests/toolchain/test_selftest.py` decodes "
        "the PNG again without spng and compares every sample bit for bit.",
        "",
        "## Failure path: Agility runtime removed",
        "",
    ]
    f_code, f_report = failure
    f_stages = {s["name"]: s for s in f_report["stages"]}
    lines += [
        f"With `D3D12\\D3D12Core.dll` deleted from a copy of the folder, `selftest` exits with "
        f"code {f_code}; `dx12-device` {f_stages['dx12-device']['status']}: "
        f'"{_cell(f_stages["dx12-device"]["reason"])}"; `compute-readback` '
        f"{f_stages['compute-readback']['status']} ({f_stages['compute-readback']['reason']}).",
        "",
        "## Link map",
        "",
        "Zig's build API has no linker-map option; `tools.toolchain.link_map` reruns the exact "
        "`lld-link` command of the build with `/MAP` added.",
        "",
        "| Archive | Members linked into `UzPainter.exe` |",
        "|---|---|",
    ]
    for archive in (CORE_ARCHIVE, *LIBCXX_ARCHIVES):
        members = link.members.get(archive, [])
        lines.append(f"| `{archive}.lib` | {len(members)}: {', '.join(members)} |")
    inspection = "passed" if link.ok else "FAILED: " + "; ".join(link.problems)
    exe_dlls = ", ".join(f"`{d}`" for d in link.exe_imports if not d.lower().startswith("api-ms-"))
    lines += [
        "",
        f"`UzPainter.exe` imports (API sets of the C runtime omitted): {exe_dlls}. No C++ "
        f"runtime DLL. Inspection: {inspection}.",
        "",
        "## DLL import closure",
        "",
        f"{len(closure.binaries)} binaries, footprint {closure.footprint:,} bytes; "
        f"{len(closure.system_imports)} distinct Windows system DLLs and API sets imported.",
        "",
        "| Binary | Size (bytes) | Role | Imports other than Windows system DLLs |",
        "|---|---|---|---|",
    ]
    for b in closure.binaries:
        own = [d for d in (*b.load_time, *b.delay_load) if not is_system(d)]
        lines.append(
            f"| `{b.path}` | {b.size:,} | {b.role} | {', '.join(f'`{d}`' for d in own) or '-'} |"
        )
    lines += [
        "",
        f"Allowlist check: {'passed' if closure.ok else 'FAILED'}"
        + ("" if closure.ok else ": " + "; ".join(closure.problems))
        + ".",
        "",
        "## Clean-machine start",
        "",
    ]
    if closure.missing_app_local:
        missing = "; ".join(
            f"`{dll}` (imported by {', '.join(users)})"
            for dll, users in closure.missing_app_local.items()
        )
        lines.append(
            f"Static closure against a clean Windows: **not closed**. Missing app-local Visual "
            f"C++ runtime: {missing}. A clean Windows 10/11 has no Visual C++ runtime, so there "
            "the `embree` stage fails with module-not-found while the process starts and every "
            "other stage runs (`embree4.dll` is loaded at run time). How the runtime ships is "
            "the owner's decision (question q1 of the task)."
        )
    else:
        lines.append(
            "Static closure against a clean Windows: closed (every import resolves inside the "
            "folder or to a Windows system DLL; the Visual C++ runtime ships app-local from "
            "`thirdparty/vc-runtime/`, release blocker RB-VCRT-TERMS)."
        )
    r_code, r_report = reduced
    r_stages = ", ".join(f"`{s['name']}` {s['status']}" for s in r_report["stages"])
    lines += [
        "",
        f"Start of a copy of the folder with the environment reduced to the Windows folders "
        f"(no Windows SDK, Vulkan SDK, Python or Zig on `PATH`), `--no-gpu`: exit code "
        f"{r_code}; {r_stages}. This machine has the Visual C++ runtime in `System32`, so this "
        "run is not a clean-machine run. The start on a clean Windows 10/11 x64 machine is "
        "the owner's own test: pending owner action.",
        "",
        "## Reproduce",
        "",
        "```",
        "python -m tools.toolchain.slice_report --work <scratch folder>",
        "python -m pytest tests/toolchain",
        "```",
        "",
    ]
    # Scratch paths of this machine are not part of the evidence.
    return "\n".join(lines).replace(str(work), "<work>")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m tools.toolchain.slice_report")
    parser.add_argument("--work", type=Path, required=True, help="scratch folder (recreated)")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    zig = shutil.which("zig")
    if zig is None:
        print("zig is not on PATH", file=sys.stderr)
        return 1
    work = args.work.resolve()
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    zig_version = subprocess.run(
        [zig, "version"], capture_output=True, text=True, check=True, timeout=60
    ).stdout.strip()
    subprocess.run(
        [zig, "build", "painter", "--prefix", str(work / "dist")],
        cwd=REPO_ROOT,
        check=True,
        timeout=3600,
    )
    bin_dir = work / "dist" / "bin"
    gpu = run_selftest(bin_dir / "UzPainter.exe", work / "run-gpu")

    no_agility = work / "no-agility"
    shutil.copytree(bin_dir, no_agility)
    (no_agility / "D3D12" / "D3D12Core.dll").unlink()
    failure = run_selftest(no_agility / "UzPainter.exe", work / "run-no-agility")

    reduced_copy = work / "reduced-env"
    shutil.copytree(bin_dir, reduced_copy)
    reduced = run_selftest(
        reduced_copy / "UzPainter.exe",
        work / "run-reduced-env",
        "--no-gpu",
        env=reduced_environment(work),
    )

    link = build_and_map(work / "linkmap", zig)
    closure = check_folder(bin_dir)
    text = render(work, zig_version, gpu, failure, reduced, link, closure)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"report written to {args.out}")
    return 0 if gpu[1]["hardware_slice"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
