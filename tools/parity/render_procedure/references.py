Vec3 = tuple[float, float, float]


def number(value: float) -> str:
    return f"{value:.6f}".replace("-0.000000", "0.000000")


def obj_text(
    header: str,
    name: str,
    faces: list[tuple[list[Vec3], list[tuple[float, float]], Vec3]],
) -> str:
    """OBJ of polygons, each with its own vertices, UVs and one flat normal."""
    lines = [
        f"# UzPainter parity fixture: {header}",
        "# Authored by UzmiGames (Apache-2.0). Iray references, task phase0.7.",
        f"o {name}",
    ]
    positions: list[str] = []
    uvs: list[str] = []
    normals: list[str] = []
    polygons: list[str] = []
    for points, coords, normal in faces:
        normals.append("vn " + " ".join(number(c) for c in normal))
        first = len(positions) + 1
        for point, coord in zip(points, coords, strict=True):
            positions.append("v " + " ".join(number(c) for c in point))
            uvs.append(f"vt {number(coord[0])} {number(coord[1])}")
        n = len(normals)
        polygons.append("f " + " ".join(f"{first + i}/{first + i}/{n}" for i in range(len(points))))
    return "\n".join(lines + positions + uvs + normals + [f"usemtl {name}"] + polygons) + "\n"


def rotate_x(point: Vec3, degrees: float) -> Vec3:
    c, s = math.cos(math.radians(degrees)), math.sin(math.radians(degrees))
    x, y, z = point
    return (x, c * y - s * z, s * y + c * z)


def rotate_y(point: Vec3, degrees: float) -> Vec3:
    c, s = math.cos(math.radians(degrees)), math.sin(math.radians(degrees))
    x, y, z = point
    return (c * x + s * z, y, -s * x + c * z)


def turn_note(yaw: float) -> str:
    return f", then turned {yaw:+g} deg about +Y" if yaw else ""


def plane_obj(yaw: float = 0.0) -> str:
    """The square in the XY plane facing +Z, tilted back (top away from the camera), then
    turned by `yaw` degrees about +Y."""
    step = 2.0 * PLANE_HALF / PLANE_QUADS
    normal = rotate_y(rotate_x((0.0, 0.0, 1.0), -PLANE_TILT), yaw)
    faces = []
    for j in range(PLANE_QUADS):
        for i in range(PLANE_QUADS):
            corners = [(i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1)]
            points = [
                rotate_y(
                    rotate_x((-PLANE_HALF + a * step, -PLANE_HALF + b * step, 0.0), -PLANE_TILT),
                    yaw,
                )
                for a, b in corners
            ]
            coords = [(a / PLANE_QUADS, b / PLANE_QUADS) for a, b in corners]
            faces.append((points, coords, normal))
    header = f"square 24 x 24, tilted back 50 deg about +X{turn_note(yaw)}"
    return obj_text(header, "uzp_plane", faces)


def cross(a: Vec3, b: Vec3) -> Vec3:
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def sub(a: Vec3, b: Vec3) -> Vec3:
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def unit(v: Vec3) -> Vec3:
    length = math.sqrt(sum(c * c for c in v))
    return (v[0] / length, v[1] / length, v[2] / length)


def chamfered_cube_polygons() -> list[list[Vec3]]:
    """Faces (inset squares), edge strips and corner triangles, counter-clockwise outside."""
    h, i = CUBE_HALF, CUBE_HALF - CUBE_CHAMFER

    def point(axis: int, signs: tuple[int, int, int]) -> Vec3:
        x, y, z = (signs[a] * (h if a == axis else i) for a in range(3))
        return (x, y, z)

    signs = [(sx, sy, sz) for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    polygons: list[list[Vec3]] = []
    for axis in range(3):
        for side in (-1, 1):
            polygons.append([point(axis, s) for s in signs if s[axis] == side])
    for a in range(3):
        for b in range(a + 1, 3):
            for sa in (-1, 1):
                for sb in (-1, 1):
                    ends = [s for s in signs if s[a] == sa and s[b] == sb]
                    polygons.append([point(axis, s) for s in ends for axis in (a, b)])
    for s in signs:
        polygons.append([point(axis, s) for axis in range(3)])
    # The solid is convex and centred on the origin, so each polygon's outward normal is the
    # direction of its centre; sort the corners counter-clockwise around it.
    ordered: list[list[Vec3]] = []
    for polygon in polygons:
        centre: Vec3 = (
            sum(p[0] for p in polygon) / len(polygon),
            sum(p[1] for p in polygon) / len(polygon),
            sum(p[2] for p in polygon) / len(polygon),
        )
        normal = unit(centre)
        u = unit(sub(polygon[0], centre))
        v = cross(normal, u)

        def angle(p: Vec3, u: Vec3 = u, v: Vec3 = v, centre: Vec3 = centre) -> float:
            d = sub(p, centre)
            return math.atan2(dot(d, v), dot(d, u))

        ordered.append(sorted(polygon, key=angle))
    return ordered


def dot(a: Vec3, b: Vec3) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def bevelled_cube_obj(yaw: float = 0.0) -> str:
    faces = []
    for polygon in chamfered_cube_polygons():
        turned = [rotate_y(rotate_x(rotate_y(p, CUBE_YAW), CUBE_PITCH), yaw) for p in polygon]
        normal = unit(cross(sub(turned[1], turned[0]), sub(turned[2], turned[0])))
        # Planar UVs of the untransformed polygon on its dominant axes, in [0, 1].
        flat = unit(cross(sub(polygon[1], polygon[0]), sub(polygon[2], polygon[0])))
        drop = max(range(3), key=lambda k: abs(flat[k]))
        keep = [k for k in range(3) if k != drop]
        coords = [
            ((p[keep[0]] / CUBE_HALF + 1.0) / 2.0, (p[keep[1]] / CUBE_HALF + 1.0) / 2.0)
            for p in polygon
        ]
        faces.append((turned, coords, normal))
    return obj_text(
        "cube of half size 7, chamfer 1.5, turned 35 deg about +Y then 25 deg about +X"
        + turn_note(yaw),
        "uzp_bevelled_cube",
        faces,
    )


def png(width: int, height: int, bit_depth: int, colour_type: int, rows: list[bytes]) -> bytes:
    def chunk(kind: bytes, body: bytes) -> bytes:
        crc = zlib.crc32(kind + body) & 0xFFFFFFFF
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", crc)

    header = struct.pack(">IIBBBBB", width, height, bit_depth, colour_type, 0, 0, 0)
    raw = b"".join(b"\x00" + row for row in rows)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )


def ridges_normal_png() -> bytes:
    """Height h(u) = sin(2 pi x / period); slope scaled so the steepest tilt is RIDGE_TILT."""
    slope = math.tan(math.radians(RIDGE_TILT))
    row = bytearray()
    for x in range(TEXTURE_SIZE):
        dh = slope * math.cos(2.0 * math.pi * (x + 0.5) / STRIPE_PERIOD)
        n = unit((-dh, 0.0, 1.0))
        row += bytes(round((c + 1.0) * 0.5 * 255) for c in n)
    return png(TEXTURE_SIZE, TEXTURE_SIZE, 8, 2, [bytes(row)] * TEXTURE_SIZE)


def opacity_stripes_png() -> bytes:
    half = STRIPE_PERIOD // 2
    row = bytes(OPACITY_CODES[(x // half) % 2] for x in range(TEXTURE_SIZE))
    return png(TEXTURE_SIZE, TEXTURE_SIZE, 8, 0, [row] * TEXTURE_SIZE)


