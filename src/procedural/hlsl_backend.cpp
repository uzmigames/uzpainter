render::KernelSource GenerateKernel(const KernelPass& pass) {
    render::KernelSource source;
    source.name = "procedural_" + pass.name;
    source.hlsl.reserve(kWrapperHead.size() + pass.body.size() + kWrapperTail.size());
    source.hlsl += kWrapperHead;
    source.hlsl += pass.body;
    source.hlsl += kWrapperTail;
    source.includes = {
        render::KernelInclude{"proc_constants.hlsli", prim::ConstantsHlsl()},
        render::KernelInclude{"proc_primitives.hlsli",
                              std::string(kPrimitivesHlsl, sizeof(kPrimitivesHlsl))},
    };
    return source;
}

std::optional<std::string> CheckInputs(const ProceduralRequest& request,
                                       const InputImages& inputs) {
    for (const auto& [name, input] : request.inputs) {
        const auto it = inputs.find(name);
        if (it == inputs.end()) return "image input " + name + " is missing";
        const Raster& raster = it->second;
        if (raster.width != input.spec.resolution || raster.height != input.spec.resolution ||
            raster.channels != input.spec.channels ||
            raster.texels.size() != size_t{raster.width} * raster.height * raster.channels) {
            return "image input " + name + " is invalid: " + std::to_string(raster.width) + "x" +
                   std::to_string(raster.height) + "x" + std::to_string(raster.channels) +
                   " texels, the request declares " + std::to_string(input.spec.resolution) +
                   "x" + std::to_string(input.spec.resolution) + "x" +
                   std::to_string(input.spec.channels);
        }
    }
    return std::nullopt;
}

std::expected<void, std::string> HlslBackend::Register(std::shared_ptr<const IHlslFamily> family) {
    if (!family) return NotRegistered(std::string("no family"));
    const FamilyRecord& record = family->Record();
    if (ObservationRefusal(record.asset)) return NotRegistered(std::string(kObservationNotExecutable));
    const std::string name = core::FormatAssetUrl(record.asset);
    if (m_families.contains(name)) return NotRegistered(name + " is already registered");
    const RasterRule& output = record.domain.output;
    if (output.formats.empty() ||
        std::any_of(output.formats.begin(), output.formats.end(),
                    [](ChannelFormat f) { return f != ChannelFormat::F32; })) {
        return NotRegistered(name + ": the HLSL host writes float32 output only");
    }
    if (output.channels.empty() ||
        std::any_of(output.channels.begin(), output.channels.end(),
                    [](uint32_t c) { return c < 1 || c > 4; })) {
        return NotRegistered(name + ": output channels must be 1 to 4");
    }
    m_families.emplace(name, std::move(family));
    return {};
}

const IHlslFamily* HlslBackend::Find(const core::AssetUrl& asset) const {
    if (ObservationRefusal(asset)) return nullptr;
    const auto it = m_families.find(core::FormatAssetUrl(asset));
    return it == m_families.end() ? nullptr : it->second.get();
}

ParityStatus HlslBackend::Status(const core::AssetUrl& asset) const {
    const IHlslFamily* family = Find(asset);
    return family ? family->Record().status : ParityStatus::Unavailable(std::string(kNoFamily));
}

std::optional<UnsupportedProcedural> HlslBackend::CandidateRefusal(
    const ProceduralRequest& request) const {
    // The reserved observation family first: Refusal, Kernels, EvaluateCandidate and
    // EvaluateReference all pass through here, and JointRefusal is never reached for it.
    if (std::optional<UnsupportedProcedural> reserved = ObservationRefusal(request.asset)) return reserved;
    const IHlslFamily* family = Find(request.asset);
    if (family == nullptr) return Refuse(AssetName(request), kNoFamily);
    if (std::optional<UnsupportedProcedural> refusal = CheckDomain(request, family->Record().domain)) {
        return refusal;
    }
    return family->JointRefusal(request);
}

std::optional<UnsupportedProcedural> HlslBackend::Refusal(const ProceduralRequest& request) const {
    if (std::optional<UnsupportedProcedural> refusal = CandidateRefusal(request)) return refusal;
    const ParityStatus& status = Find(request.asset)->Record().status;
    if (status.kind != ParityStatus::Kind::Exact) {
        return UnsupportedProcedural{AssetName(request), std::string(kNotCertified), "status",
                                     std::string(KindName(status.kind)), "\"exact\""};
    }
    return std::nullopt;
}

bool HlslBackend::CanEvaluate(const ProceduralRequest& request) const {
    return !Refusal(request).has_value();
}

std::expected<std::vector<render::KernelSource>, UnsupportedProcedural> HlslBackend::Kernels(
    const ProceduralRequest& request) const {
    if (std::optional<UnsupportedProcedural> refusal = CandidateRefusal(request)) {
        return Refused(*refusal);
    }
    std::vector<render::KernelSource> sources;
    for (const KernelPass& pass : Find(request.asset)->Plan(request)) {
        sources.push_back(GenerateKernel(pass));
    }
    return sources;
}

RasterFuture HlslBackend::Run(const ProceduralRequest& request, const InputImages& inputs) {
    if (std::optional<std::string> invalid = CheckInputs(request, inputs)) return Ready(Failed(*invalid));
    if (m_engine == nullptr) {
        return Ready(render::Fail(render::ErrorCode::GpuBackendUnavailable, std::nullopt,
                                  "the HLSL backend has no GPU engine"));
    }
    auto job = std::make_shared<Job>();
    job->request = request;
    job->inputs = inputs;
    job->passes = Find(request.asset)->Plan(request);
    if (job->passes.empty()) return Ready(Failed(AssetName(request) + ": the family planned no pass"));
    for (size_t i = 0; i < job->passes.size(); ++i) {
        const KernelPass& pass = job->passes[i];
        if (pass.inputs.size() > kMaxPassInputs) {
            return Ready(Failed(AssetName(request) + ": pass " + pass.name + " has more than " +
                                std::to_string(kMaxPassInputs) + " inputs"));
        }
        for (const PassInput& input : pass.inputs) {
            const bool earlier = input.pass >= 0 && static_cast<size_t>(input.pass) < i;
            if (input.pass >= 0 ? !earlier : !inputs.contains(input.requestInput)) {
                return Ready(Failed(AssetName(request) + ": pass " + pass.name +
                                    " reads an input that is neither an earlier pass nor a request input"));
            }
        }
        job->kernels.push_back(GenerateKernel(pass));
    }
    return m_engine->Submit(std::shared_ptr<const Job>(job),
                            [](render::EngineContext& context, const Job& work) {
                                return RunJob(context, work);
                            });
}

RasterFuture HlslBackend::Evaluate(const ProceduralRequest& request, const InputImages& inputs) {
    if (std::optional<UnsupportedProcedural> refusal = Refusal(request)) {
        return Ready(Failed(refusal->Describe()));
    }
    return Run(request, inputs);
}

RasterFuture HlslBackend::EvaluateCandidate(const ProceduralRequest& request,
                                            const InputImages& inputs) {
    if (std::optional<UnsupportedProcedural> refusal = CandidateRefusal(request)) {
        return Ready(Failed(refusal->Describe()));
    }
    return Run(request, inputs);
}

render::Result<Raster> HlslBackend::EvaluateReference(const ProceduralRequest& request,
                                                      const InputImages& inputs) const {
    if (std::optional<UnsupportedProcedural> refusal = CandidateRefusal(request)) {
        return Failed(refusal->Describe());
    }
    if (std::optional<std::string> invalid = CheckInputs(request, inputs)) return Failed(*invalid);
    return Find(request.asset)->Reference(request, inputs);
}

