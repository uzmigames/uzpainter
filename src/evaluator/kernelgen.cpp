void AppendUintTable(std::string& text, const char* name, const uint32_t* values, size_t count) {
    text += "static const uint ";
    text += name;
    text += "[";
    text += std::to_string(count);
    text += "] = {";
    char buffer[16];
    for (size_t i = 0; i < count; ++i) {
        std::snprintf(buffer, sizeof(buffer), "%s0x%08Xu", i == 0 ? "" : ",", values[i]);
        text += buffer;
    }
    text += "};\n";
}

