namespace resample_detail {

Result<void> CheckColourMode(const IDevice& device, ImagePassFormat format, ColourMode colour) {
    if (colour == ColourMode::Srgb && format.encoding != TexelEncoding::Unorm8) {
        return Invalid(device, "sRGB filtering needs an 8-bit unorm format");
    }
    if (colour == ColourMode::Normal && format.channels != 4) {
        return Invalid(device, "normal filtering needs a four-channel format");
    }
    return {};
}

Result<ResampleDispatch> Prepare(EngineContext& context, uz::RHIFormat rhiFormat,
                                 uz::RHITextureHandle source, uint32_t srcWidth,
                                 uint32_t srcHeight, uz::RHITextureHandle destination,
                                 uint32_t dstWidth, uint32_t dstHeight,
                                 const ResampleOptions& options) {
    IDevice& device = context.Device();
    const ImagePassFormat format = *ImagePassFormatOf(rhiFormat);
    Result<ComputeKernel> kernel = context.Kernel(ResampleKernel(device, rhiFormat));
    if (!kernel) return Unexpected(kernel.error());
    const uint32_t gx = std::gcd(srcWidth, dstWidth);
    const uint32_t gy = std::gcd(srcHeight, dstHeight);
    const uint32_t ax = dstWidth / gx;
    const uint32_t bx = srcWidth / gx;
    const uint32_t ay = dstHeight / gy;
    const uint32_t by = srcHeight / gy;
    const float invTotal =
        static_cast<float>(1.0 / (static_cast<double>(bx) * static_cast<double>(by)));
    const uint32_t mode = static_cast<uint32_t>(options.filter) |
                          static_cast<uint32_t>(options.wrap) << 4 |
                          static_cast<uint32_t>(options.colour) << 8 |
                          EncodingConstant(format.encoding) << 12 | format.channels << 16;
    ResampleDispatch dispatch(device);
    dispatch.kernel = *kernel;
    const uint32_t srcName = dispatch.bindings.Texture(source);
    const uint32_t dstName = dispatch.bindings.Output(destination);
    if (Result<void> named = dispatch.bindings.Validate(); !named) {
        return Unexpected(named.error());
    }
    dispatch.constants = {srcWidth, srcHeight, dstWidth, dstHeight, mode, srcName, dstName,
                          ax,       bx,        ay,       by,        std::bit_cast<uint32_t>(invTotal)};
    dispatch.groupsX = Groups(dstWidth, 8);
    dispatch.groupsY = Groups(dstHeight, 8);
    return dispatch;
}

void Record(uz::IRHICommandList& cmd, const ResampleDispatch& dispatch) {
    cmd.SetPipeline(dispatch.kernel.pipeline);
    dispatch.bindings.Record(cmd, dispatch.constants);
    cmd.Dispatch(dispatch.groupsX, dispatch.groupsY, 1);
}

}  // namespace resample_detail

Result<void> Resample(EngineContext& context, uz::RHITextureHandle source,
                      uz::RHITextureHandle destination, const ResampleOptions& options) {
    IDevice& device = context.Device();
    Result<uz::RHITextureDesc> src =
        RequireTexture(device, source, uz::RHITextureUsage::None, "source");
    if (!src) return Unexpected(src.error());
    Result<uz::RHITextureDesc> dst =
        RequireTexture(device, destination, uz::RHITextureUsage::None, "destination");
    if (!dst) return Unexpected(dst.error());
    if (SameTexture(source, destination)) {
        return Invalid(device, "the source and destination are the same texture");
    }
    if (src->format != dst->format) {
        return Invalid(device, "the source and destination formats differ");
    }
    const ImagePassFormat format = *ImagePassFormatOf(src->format);
    Result<void> mode = resample_detail::CheckColourMode(device, format, options.colour);
    if (!mode) return mode;

    if (src->width == dst->width && src->height == dst->height) {
        Result<uz::RHITextureDesc> copySrc =
            RequireTexture(device, source, uz::RHITextureUsage::CopySrc, "source");
        if (!copySrc) return Unexpected(copySrc.error());
        Result<uz::RHITextureDesc> copyDst =
            RequireTexture(device, destination, uz::RHITextureUsage::CopyDst, "destination");
        if (!copyDst) return Unexpected(copyDst.error());
        return context.SubmitAndWait([&](uz::IRHICommandList& cmd) {
            const uz::RHIBarrierDesc before[2] = {
                Transition(source, State::Common, State::CopySrc),
                Transition(destination, State::Common, State::CopyDst)};
            cmd.ResourceBarrier(before, 2);
            CopyMip(device, cmd, source, destination, 0, format, src->width, uz::RHIBufferHandle::Invalid());
            const uz::RHIBarrierDesc after[2] = {
                Transition(source, State::CopySrc, State::Common),
                Transition(destination, State::CopyDst, State::Common)};
            cmd.ResourceBarrier(after, 2);
        });
    }

    Result<uz::RHITextureDesc> readable =
        RequireTexture(device, source, uz::RHITextureUsage::ShaderResource, "source");
    if (!readable) return Unexpected(readable.error());
    Result<uz::RHITextureDesc> writable =
        RequireTexture(device, destination, uz::RHITextureUsage::UnorderedAccess, "destination");
    if (!writable) return Unexpected(writable.error());
    Result<resample_detail::ResampleDispatch> dispatch =
        resample_detail::Prepare(context, src->format, source, src->width, src->height,
                                 destination, dst->width, dst->height, options);
    if (!dispatch) return Unexpected(dispatch.error());
    return context.SubmitAndWait([&](uz::IRHICommandList& cmd) {
        const uz::RHIBarrierDesc before[2] = {
            Transition(source, State::Common, State::ShaderResource),
            Transition(destination, State::Common, State::UnorderedAccess)};
        cmd.ResourceBarrier(before, 2);
        resample_detail::Record(cmd, *dispatch);
        const uz::RHIBarrierDesc after[2] = {
            Transition(source, State::ShaderResource, State::Common),
            Transition(destination, State::UnorderedAccess, State::Common)};
        cmd.ResourceBarrier(after, 2);
    });
}

