def input_entry(input_id: str, kind: str, path: str, data: bytes) -> dict[str, Any]:
    return {
        "input_id": input_id,
        "kind": kind,
        "path": path,
        "sha256": sha256_bytes(data),
        "provenance": {"origin": "uzmigames_authored", "licence": "Apache-2.0"},
    }


def mesh_input(fixture: Fixture) -> dict[str, Any]:
    if fixture.mesh == "sphere":
        data = (REPO_ROOT / SPHERE_PATH).read_bytes()
        return input_entry("sphere", "mesh", SPHERE_PATH, data)
    name = f"{fixture.mesh}.obj"
    return input_entry(
        fixture.mesh, "mesh", f"parity/fixtures/iray-references/{name}", committed_fixtures()[name]
    )


def setting(name: str, value: Any, applied_by: str, unit: str | None = None) -> dict[str, Any]:
    item: dict[str, Any] = {"name": name, "value": value, "applied_by": applied_by}
    return item | ({"unit": unit} if unit else {})


def operator_sheet(fixture: Fixture) -> list[dict[str, Any]]:
    """The v2 Iray sheet, with the ref_match clear colour and rotation where it applies."""
    sheet = []
    for item in V2_SHEET:
        value: Any = item.value
        name = f"{item.panel}/{item.setting}"
        if fixture.preset == "ref_match" and name == f"{DISPLAY_PANEL}/Clear color value":
            value = REF_MATCH_CLEAR_COLOUR
        if fixture.preset == "ref_match" and name == f"{DISPLAY_PANEL}/Environment Rotation":
            value = fixture.rotation
        sheet.append(setting(name, value, "operator_settings_sheet", item.unit))
    return sheet


def capture_sheet(fixture: Fixture) -> list[dict[str, Any]]:
    background = REF_MATCH_BACKGROUND if fixture.preset == "ref_match" else V2_BACKGROUND
    values: list[tuple[str, Any]] = [
        ("capture.procedure", PROCEDURE_VERSION),
        ("capture.route", SAVE_RENDER),
        ("capture.encoding", "display_referred"),
        ("capture.bits_per_channel", 16),
        ("capture.background_srgb8", background),
        ("capture.display_transform", "Default - sRGB"),
        ("capture.camera_rotation_order", "ZYX"),
    ]
    return [setting(name, value, "recorder_api") for name, value in values]


def instruction_steps(fixture: Fixture) -> list[dict[str, Any]]:
    calls: list[tuple[str, dict[str, Any]]] = [
        (ps.CREATE, {"mesh": mesh_input(fixture)["input_id"]}),
        (ps.CAMERA + "projection_type", {"value": "Perspective"}),
        (ps.CAMERA + "position", {"value": [0.0, 0.0, CAMERA_DISTANCE]}),
        (ps.CAMERA + "rotation", {"value": [0.0, 0.0, 0.0]}),
        (ps.CAMERA + "field_of_view", {"value": FIELD_OF_VIEW}),
        (ps.CAMERA + "aperture", {"value": 0.0}),
    ]
    if fixture.preset == "ref_match":
        calls.append(
            (
                ps.SET_ENVIRONMENT,
                {"session_environment": REF_MATCH_HDRI_SHA256, "file_name": REF_MATCH_HDRI_NAME},
            )
        )
    else:
        calls.append((ps.SET_ENVIRONMENT, {"resource_url": STUDIO_WHITE_SOFT}))
    extra = fixture.perturbation
    if extra is not None and extra.add_format is not None:
        calls.append((ps.ADD_CHANNEL, {"channel": extra.channel, "format": extra.add_format}))
    resource_step = None
    if extra is not None and extra.bitmap is not None:
        calls.append((ps.IMPORT_RESOURCE, {"input": input_id(extra.bitmap), "usage": "TEXTURE"}))
        resource_step = len(calls)
    calls.append((ps.INSERT_FILL, {"position": "top"}))
    fill = len(calls)
    channels = ["BaseColor", "BaseMetalness", "SpecularRoughness"]
    if extra is not None:
        channels.append(extra.channel)
    calls.append((ps.SET_ACTIVE_CHANNELS, {"node_step": fill, "channels": channels}))
    calls.append(
        (
            ps.SET_SOURCE,
            {
                "node_step": fill,
                "channel": "BaseColor",
                "color": list(fixture.base_srgb),
                "color_space": "sRGB",
            },
        )
    )
    scalars = (("BaseMetalness", fixture.metalness), ("SpecularRoughness", fixture.roughness))
    for channel, value in scalars:
        calls.append(
            (
                ps.SET_SOURCE,
                {"node_step": fill, "channel": channel, "color": [value] * 3, "color_space": "Raw"},
            )
        )
    if extra is not None:
        args: dict[str, Any] = {"node_step": fill, "channel": extra.channel}
        if resource_step is not None:
            args["resource_step"] = resource_step
        else:
            assert extra.color is not None
            args |= {"color": list(extra.color), "color_space": extra.color_space}
        calls.append((ps.SET_SOURCE, args))
    return [
        {"step": number_, "call": call, "args": args_}
        for number_, (call, args_) in enumerate(calls, start=1)
    ]


def input_id(file_name: str) -> str:
    return file_name.rsplit(".", 1)[0]


def description(fixture: Fixture) -> str:
    material = (
        f"base colour sRGB {list(fixture.base_srgb)}, metalness {fixture.metalness:g}, "
        f"roughness {fixture.roughness:g}"
    )
    if fixture.perturbation is not None:
        extra = fixture.perturbation
        source = extra.bitmap or f"uniform {list(extra.color or ())} ({extra.color_space})"
        material += f", plus {extra.channel} from {source}"
    if fixture.preset == "ref_match":
        light = (
            "the ref_match v3 preset (the standard's HDRI imported as a session resource, SHA-256 "
            f"{REF_MATCH_HDRI_SHA256}, clear colour 141,142,148, environment rotation "
            f"{fixture.rotation:g})"
        )
    else:
        light = "the v2 common block (Studio White Soft by resource URL, clear colour 89,89,89)"
    if fixture.group == STABILITY:
        kind = "Iray stability probe fixture"
        task = "phase0.9_render-reference-capture under the fixed render pipeline (decisions 038, "
        task += "039, 052, 062)"
        renders = "two references at 256 samples, no k*S reference; stability evidence, not an "
        renders += "admitted golden"
    else:
        kind = "Iray reference fixture"
        task = "phase0.7_render-reference-captures under the fixed render pipeline (decisions "
        task += "038, 039, 046)"
        renders = "two session-separated references and one at 4 x 256 samples"
    return (
        f"{kind} {fixture.name} ({fixture.role}) of task {task}: the {fixture.mesh} with one fill "
        f"layer ({material}), shader at Painter's defaults, under {light}, OCIO with Painter's "
        "substance config and Default - sRGB, camera on +Z at 60 looking at the origin, field of "
        "view 40, captured by procedure iray-capture/1 (Save Render, 16-bit PNG, 1200x1200, 256 "
        f"samples; {renders}). Fixture values proposed to the owner, not ratified."
    )


def manifest(fixture: Fixture) -> dict[str, Any]:
    inputs = [mesh_input(fixture)]
    extra = fixture.perturbation
    if extra is not None and extra.bitmap is not None:
        inputs.append(
            input_entry(
                input_id(extra.bitmap),
                "image",
                f"parity/fixtures/iray-references/{extra.bitmap}",
                committed_fixtures()[extra.bitmap],
            )
        )
    return {
        "schema": "uzpainter/parity/golden-public/1",
        "record_class": "public_manifest",
        "golden_id": fixture.golden_id,
        "tier": "3",
        "domain": f"phase0/{fixture.group}",
        "description": description(fixture),
        "inputs": inputs,
        "instruction_sequence": {
            "author": "UzmiGames",
            "interface": "substance_painter_documented_python_api",
            "steps": instruction_steps(fixture),
        },
        "applied_settings": operator_sheet(fixture) + capture_sheet(fixture),
        "uncontrolled_settings": ["random_seed"],
        "expectations": [],
        "software": {"painter": dict(PAINTER), "uzpainter_build_hash": None},
        "private_records": [],
    }


def manifest_path(fixture: Fixture, directory: Path | None = None) -> Path:
    if directory is None:
        directory = STABILITY_DIR if fixture.group == STABILITY else MANIFEST_DIR
    return directory / f"{fixture.name}.json"


def write_manifests(
    directory: Path = MANIFEST_DIR, stability_directory: Path = STABILITY_DIR
) -> list[Path]:
    """Write every fixture's manifest, keeping the private records already merged into it."""
    written = []
    for fixture in (*FIXTURES, *STABILITY_FIXTURES):
        folder = stability_directory if fixture.group == STABILITY else directory
        folder.mkdir(parents=True, exist_ok=True)
        path = manifest_path(fixture, folder)
        document = manifest(fixture)
        if path.is_file():
            document["private_records"] = json.loads(path.read_text(encoding="utf-8"))[
                "private_records"
            ]
        path.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8", newline="\n")
        written.append(path)
    return written


def reference_manifests() -> list[Path]:
    """Every manifest of the Iray reference set: the fixtures and the qualification sphere."""
    return [QUALIFICATION_MANIFEST, *(manifest_path(f) for f in FIXTURES)]


def stability_manifests() -> list[Path]:
    """The manifests of decision 052's capture request (stability probe, decision 062)."""
    return [manifest_path(f) for f in STABILITY_FIXTURES]
