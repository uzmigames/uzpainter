render::KernelInclude TablesInclude() {
    static const render::KernelInclude include = [] {
        uint32_t srgbOperand[256];
        uint32_t unorm8Operand[256];
        uint32_t thresholdLo[256];
        uint32_t thresholdHi[256];
        const std::array<float, 256>& srgb = arith::Srgb8OperandTable();
        const std::array<float, 256>& unorm8 = arith::Unorm8OperandTable();
        const std::array<double, 256>& thresholds = arith::Srgb8Thresholds();
        for (size_t i = 0; i < 256; ++i) {
            srgbOperand[i] = std::bit_cast<uint32_t>(srgb[i]);
            unorm8Operand[i] = std::bit_cast<uint32_t>(unorm8[i]);
            const uint64_t bits = std::bit_cast<uint64_t>(thresholds[i]);
            thresholdLo[i] = static_cast<uint32_t>(bits & 0xFFFFFFFFu);
            thresholdHi[i] = static_cast<uint32_t>(bits >> 32);
        }
        std::string text = "// Generated by src/evaluator/kernelgen.cpp from arith.h.\n";
        AppendUintTable(text, "kSrgb8Operand", srgbOperand, 256);
        AppendUintTable(text, "kUnorm8Operand", unorm8Operand, 256);
        AppendUintTable(text, "kSrgb8ThresholdLo", thresholdLo, 256);
        AppendUintTable(text, "kSrgb8ThresholdHi", thresholdHi, 256);
        const uint32_t colour[2] = {std::bit_cast<uint32_t>(arith::kHsvEpsilon),
                                    std::bit_cast<uint32_t>(arith::kHalfPi)};
        AppendUintTable(text, "kColourConstants", colour, 2);
        text += "#define UZP_TABLE_UNORM16 " + std::to_string(kTableUnorm16) + "u\n";
        text += "#define UZP_TABLE_RCP " + std::to_string(kTableRcp) + "u\n";
        text += "#define UZP_TABLE_SQRT " + std::to_string(kTableSqrt) + "u\n";
        text += "#define UZP_TABLE_RSQRT " + std::to_string(kTableRsqrt) + "u\n";
        text += "#define UZP_POW_LOG2HI " + std::to_string(kPowLog2Hi) + "u\n";
        text += "#define UZP_POW_LOG2LO " + std::to_string(kPowLog2Lo) + "u\n";
        text += "#define UZP_POW_EXP2POS " + std::to_string(kPowExp2Pos) + "u\n";
        text += "#define UZP_POW_EXP2NEG " + std::to_string(kPowExp2Neg) + "u\n";
        text += "#define UZP_POW_SIN " + std::to_string(kPowSin) + "u\n";
        text += "#define UZP_POW_COS " + std::to_string(kPowCos) + "u\n";
        return render::KernelInclude{"evaluator_tables.hlsli", std::move(text)};
    }();
    return include;
}

const std::vector<uint32_t>& OperandTableWords() {
    static const std::vector<uint32_t> words = [] {
        std::vector<uint32_t> out;
        out.reserve(kTableWords);
        for (const float value : arith::Unorm16OperandTable()) out.push_back(std::bit_cast<uint32_t>(value));
        for (const hw::Op op : {hw::Op::Rcp, hw::Op::Sqrt, hw::Op::Rsqrt}) {
            const std::vector<uint32_t>& table = hw::Words(op);
            out.insert(out.end(), table.begin(), table.end());
        }
        return out;
    }();
    return words;
}

render::KernelSource BlendKernelSource(const BlendKernelVariant& variant) {
    const bool halfCoverage = variant.format.alpha && variant.format.halfCoverage;
    const bool fromHalf = halfCoverage && variant.format.halfCoverageFromHalf;
    render::KernelSource source;
    source.name = "evaluator_blend_" + std::string(core::ToString(variant.mode)) + "_" +
                  std::to_string(variant.format.BytesPerChannel() * 8) +
                  (variant.format.IsUnorm() ? (variant.format.srgb ? "srgb" : "unorm") : "float") +
                  "_c" + std::to_string(variant.format.channels) + (variant.format.alpha ? "a" : "") +
                  (halfCoverage ? (fromHalf ? "h2" : "h") : "") + (variant.rawOutput ? "_raw" : "");
    source.hlsl = std::string(kBlendHlsl, sizeof(kBlendHlsl));
    source.entryPoint = "main";
    source.defines = {
        "UZP_MODE_" + std::string(core::ToString(variant.mode)) + "=1",
        "UZP_ENC=" + std::to_string(render::image_pass_detail::EncodingConstant(variant.format.encoding)),
        "UZP_CHANNELS=" + std::to_string(variant.format.channels),
        std::string("UZP_SRGB=") + (variant.format.srgb ? "1" : "0"),
        std::string("UZP_ALPHA=") + (variant.format.alpha ? "1" : "0"),
        std::string("UZP_HALF_COVERAGE=") + (halfCoverage ? (fromHalf ? "2" : "1") : "0"),
        std::string("UZP_RAW_OUTPUT=") + (variant.rawOutput ? "1" : "0"),
    };
    source.includes = {render::image_pass_detail::CommonInclude(), TablesInclude()};
    return source;
}

std::array<uint32_t, kBlendParamsStride> EncodeBlendParams(const BlendOp& op,
                                                           const BlendBindings& bindings) {
    std::array<uint32_t, kBlendParamsStride> params{};
    params[kParamWidth] = bindings.width;
    params[kParamHeight] = bindings.height;
    uint32_t flags = 0;
    if (op.acc.kind == Operand::Kind::Tile) flags |= kFlagAccIsTile;
    if (op.source.kind == Operand::Kind::Tile) flags |= kFlagSrcIsTile;
    if (op.mask.kind == Operand::Kind::Tile) flags |= kFlagMaskIsTile;
    if (bindings.accAlpha) flags |= kFlagAccAlpha;
    if (bindings.srcAlpha) flags |= kFlagSrcAlpha;
    if (op.effectMix) flags |= kFlagEffectMix;
    if (op.coverageWeights) flags |= kFlagCoverageWeights;
    if (op.emptyBackdrop) flags |= kFlagEmptyBackdrop;
    if (op.fusedReadout) flags |= kFlagFusedReadout;
    params[kParamFlags] = flags;
    params[kParamAccIndex] = bindings.accSrv;
    for (size_t i = 0; i < 4; ++i) params[kParamAccConst + i] = std::bit_cast<uint32_t>(op.acc.value[i]);
    params[kParamSrcIndex] = bindings.srcSrv;
    for (size_t i = 0; i < 4; ++i) {
        params[kParamSrcConst + i] = std::bit_cast<uint32_t>(op.source.value[i]);
    }
    params[kParamMaskIndex] = bindings.maskSrv;
    params[kParamMaskConst] = std::bit_cast<uint32_t>(op.mask.value[0]);
    params[kParamOpacity] = std::bit_cast<uint32_t>(op.opacity);
    params[kParamDstUav] = bindings.dstUav;
    params[kParamTable16Srv] = bindings.table16Srv;
    params[kParamMaskEncoding] = render::image_pass_detail::EncodingConstant(bindings.maskEncoding);
    params[kParamPowSrv] = bindings.powSrv;
    return params;
}

