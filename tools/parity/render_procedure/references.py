"""Iray reference fixtures of the fixed render pipeline (task `phase0.7_render-reference-captures`,
decisions 038, 039 and 046), and the stability probe of decision 052's capture request (task
`phase0.9_render-reference-capture`, decision 062).

Every fixture is UzmiGames-authored content (Apache-2.0, generated by this code) rendered under
one preset of the Assets3D render comparison standard:

- `v2`: the standard's common block, Studio White Soft named by its resource URL, clear colour
  89,89,89 (`iray_probe.V2_SHEET`);
- `ref_match`: the v3 preset, the standard's HDRI imported as a session resource (named in the
  instruction sequence by its SHA-256, the file itself stays in Assets3D), clear colour
  141,142,148, environment rotation 0 (front view) or 180 (back view).

Committed inputs (`parity/fixtures/iray-references/`), regenerated byte-identically by
`python -m tools.parity.render_procedure references`:

- `plane.obj`: a 24 x 24 square of 8 x 8 quads tilted back by `PLANE_TILT` degrees about +X.
- `bevelled-cube.obj`: a cube of half size 7 with chamfered edges (one 1.5-unit chamfer
  segment, flat normals), turned `CUBE_YAW` about +Y then `CUBE_PITCH` about +X so that three
  faces face the camera.
- `ridges-normal.png`: 8-bit RGB tangent-space normal map, ridges along U (period 32 px, slopes
  up to `RIDGE_TILT` degrees). Its green channel is constant, so it reads the same in the
  OpenGL and DirectX conventions.
- `stripes-height.png`: 16-bit grey height map, vertical stripes of 0 and 1 (period 32 px).
- `opacity-stripes.png`: 8-bit grey, vertical stripes of 0.25 and 0.75 (period 32 px).
- `plane-yaw-{p1,m1}.obj`, `bevelled-cube-yaw-{p1,m1}.obj`: the plane and the bevelled cube
  turned by +1 and -1 degree about +Y after their own transforms (stability probe), so no facet
  normal has an x component of exactly zero.

The sphere is the procedure's `parity/fixtures/render-procedure/sphere.obj`. The camera sits on
+Z at 60 units looking at the origin, field of view 40 degrees, aperture 0, no rotation (no Euler
order is involved). Materials are one fill layer of uniform sources through the documented
Python API on the template's OpenPBR channels (`BaseColor` in sRGB, `BaseMetalness` and
`SpecularRoughness` raw); a perturbation adds one more channel to the same fill. The shader stays
Painter's default instance at its defaults (decision 038). The values are a proposal to the owner
(task item 2.7), not ratified.

The manifests (`parity/envelopes/<current>/manifests/phase0/iray-references/<golden>.json`) are
generated from the same table; `write_manifests` keeps the `private_records` the store merged in.

`STABILITY_FIXTURES` are the nine goldens of decision 052's capture request
(`phase0/iray-stability/<golden>`): the plane and the cube turned by +-1 degree, repeats of
`plane-mid-grey` (two sessions, and two renders in one session) and of
`cube-saturated--ref-match-180`, and the plane under `ref_match` at 0 and 180 degrees. Each holds
two S renders and no k*S render: they are stability evidence, never admitted as goldens. A
repeat keeps its parent's instruction sequence, so its golden key equals the parent's.
"""

