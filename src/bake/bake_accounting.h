#pragma once

// Evidence maps and used-surface accounting of a bake (phase3.3_baker-evidence-publication,
// `docs/architecture/06-baking.md` §4, BAK-04 and BAK-07, decision 347).
//
// - The **used surface** is the conservative coverage: the texels whose open square overlaps the
//   interior of a low UV triangle (`ConservativeCoverage`). Every texel the baker samples (its
//   class is not `Uncovered`) lies in it; the others in it are the **ring**.
// - Its seven classes are disjoint and sum to `coverage.conservative_texels`: straight hits, cage
//   hits, misses (sampled texels without a front hit: centre misses and back-face hits), hidden
//   texels (the request's mask), ring texels the compatible map extends into from neighbouring hits
//   (AO's `DilationWidth`), ring texels it holds no value for, and repaired texels (always 0:
//   UzPainter never repairs on its own).
// - `fallback_texels` counts used texels set to a neutral value, only with the request's
//   `neutral_fallback` (Normal only). `padding_texels` lie outside the used surface;
//   `changed_used_texels` counts used texels whose compatible map differs from RAW.
// - The evidence files of a usage (`EvidenceFiles`) are its compatible map, `raw`, `hit`,
//   `coverage`, `miss` and `extension`, under `cache/bake/<key>/<usage>/`. They are a pure function of
//   the request and the result, so a deleted file is regenerated byte for byte by baking the same
//   request again; nothing here writes the compatible map.
//
// Parity with Painter is not claimed: every usage stays `pending-evidence`.

#include <array>
#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <vector>

#include "bake/bake_request.h"

namespace uzp::bake {

/// The conservative used surface of `low` at `width` x `height` (row 0 at v = 1): 1 where the
/// texel's open square overlaps the interior of a UV triangle with a nonzero UV area (the
/// separating-axis test with strict overlap on the two box axes and the three edge normals).
std::vector<std::uint8_t> ConservativeCoverage(const std::vector<const BakeMesh*>& low, std::uint32_t width,
                                               std::uint32_t height);

/// Raises `uzp::core::NotYetSupported` when `neutral_fallback` is set with a usage other than
/// Normal: no neutral value is established for it. Called before any work.
void ValidateFallback(const BakeRequest& request);

/// The RGB16 codes of the flat tangent normal (0, 0, 1) under `format` (the Normal encoding of
/// `06-baking.md` §3.2: 32768, 32768 or 32767 for DirectX, 65535).
std::array<std::uint16_t, 3> NeutralNormalCodes(core::NormalMapFormat format);

/// Sets every used-surface texel of `result.normal` without a hit to `NeutralNormalCodes`; RAW
/// is kept. Returns their count.
std::uint64_t ApplyNeutralFallback(BakeResult& result);

/// `fidelity_evidence`: `diagnostic_only` for a diagnostic bake or a repaired texel,
/// `contains_fallback` when a used texel holds the neutral fallback, `used_surface_as_baked`
/// otherwise.
enum class FidelityEvidence { UsedSurfaceAsBaked, ContainsFallback, DiagnosticOnly };

const char* FidelityEvidenceName(FidelityEvidence evidence);

struct CoverageCounts {
    std::uint64_t centre_texels = 0;        // sampled texels (SubSampling 1: centre in a UV triangle)
    std::uint64_t conservative_texels = 0;  // the used surface
};

struct UsedSurfaceCounts {
    std::uint64_t hit_straight = 0;
    std::uint64_t hit_cage = 0;
    std::uint64_t miss = 0;
    std::uint64_t hidden = 0;
    std::uint64_t ring_extended = 0;
    std::uint64_t ring_no_hit_neighbour = 0;
    std::uint64_t repaired = 0;

    std::uint64_t Total() const {
        return hit_straight + hit_cage + miss + hidden + ring_extended + ring_no_hit_neighbour + repaired;
    }
};

/// One low part's sampled texels (a texel belongs to the part of its first covered sub-sample).
/// `z_negative_texels`: Normal only, hit texels whose RAW blue code encodes a negative tangent Z
/// (below 32768), an inspection signal never used to change a value.
struct PartCounts {
    std::string name;
    std::uint64_t hits = 0;
    std::uint64_t misses = 0;
    std::optional<std::uint64_t> z_negative_texels;
};

struct UsageAccount {
    MeshMapUsage usage = MeshMapUsage::AO;
    CoverageCounts coverage;
    UsedSurfaceCounts used_surface;
    std::uint64_t fallback_texels = 0;
    std::uint64_t padding_texels = 0;
    std::uint64_t changed_used_texels = 0;
    /// A used texel differs from what the ray baked: a fallback or a repair (a ring extension is
    /// edge extension, not a modification).
    bool surface_modified = false;
    FidelityEvidence fidelity_evidence = FidelityEvidence::UsedSurfaceAsBaked;
    std::vector<PartCounts> parts;
};

/// The accounting of `usage` in `result` (baked from `request`). Throws `std::logic_error` when a
/// sampled texel lies outside the used surface or the classes do not sum to it (an internal
/// invariant), `uzp::core::ValueError` when `usage` was not baked.
UsageAccount AccountUsage(const BakeRequest& request, const BakeResult& result, MeshMapUsage usage);

/// A map as stored: `channels` samples per texel, rows top first, in one of `u8`, `u16` or `f32`.
struct MapImage {
    std::uint32_t width = 0;
    std::uint32_t height = 0;
    std::uint32_t channels = 0;
    std::vector<std::uint8_t> u8;
    std::vector<std::uint16_t> u16;
    std::vector<float> f32;
};

/// The compatible map of `usage` (AO L16, Normal RGB16, WorldSpaceNormal xyz, Position 1 or 3
/// channels, ID labels, Opacity, Height); none for Thickness, which has no per-texel value.
std::optional<MapImage> CompatibleMap(const BakeResult& result, MeshMapUsage usage);

/// The RAW map of `usage`: before dilation and fallback (AO `ao_raw`, Normal `normal_raw`; the map
/// itself for the others); none for Thickness.
std::optional<MapImage> RawMap(const BakeResult& result, MeshMapUsage usage);

/// The file of `image`: a PNG (UzPainter's export encoder) for 8- and 16-bit samples, and for
/// float32 samples the evidence container `UZPF32\0\0` followed by the width, height and channel
/// count (uint32 little-endian) and the samples' IEEE bits little-endian.
std::string EncodeMapFile(const MapImage& image);

/// The extension of `EncodeMapFile(image)`: `.png` or `.f32`.
const char* MapFileExtension(const MapImage& image);

/// `cache/bake/<key>`: `key` is the first 16 hexadecimal digits of the SHA-256 of
/// `texture_set + "\n" + input_revision`.
std::string EvidenceDirectory(const BakeRequest& request);

struct EvidenceFile {
    std::string path;  // relative, '/'-separated, beginning with `cache/`
    std::string bytes;
    std::string sha256;
};

/// Per enabled usage, in request order: `map`, `raw` (none for Thickness), then the 8-bit masks
/// `hit` (1 straight, 2 cage), `coverage` (bit 0 sampled, bit 1 used surface), `miss` (1 on the miss
/// class) and `extension` (1 where the compatible map was extended from neighbouring hits).
std::vector<EvidenceFile> EvidenceFiles(const BakeRequest& request, const BakeResult& result);

/// Writes `files` under `root` (each through a temporary file renamed over its path). Throws
/// `uzp::core::ValueError` when a file cannot be written.
void WriteEvidence(const std::filesystem::path& root, const std::vector<EvidenceFile>& files);

}  // namespace uzp::bake
