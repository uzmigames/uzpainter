"""The native copy of Painter's OCIO decode of an sRGB uniform colour (decisions 202 and 212).

`python/uzpainter_facade/ocio_srgb.py` is the one source of the measured table. This module
renders it as `src/evaluator/ocio_srgb_table.inc`, the entries of the native table
(`evaluator::PainterOcioSrgbDecode`, `src/evaluator/sources.h`), so the native module and the
facade read the same values. Keys are exactly the facade's: the float32 bits of `c / 255` for each
code `c` and of each other recorded component, a recorded component overriding a code of the same
bits as in the facade's dict.

    python tools/parity/ocio_srgb_table.py           # rewrite the .inc
    python tools/parity/ocio_srgb_table.py --check   # exit 1 when the .inc is stale

`tests/parity/test_ocio_srgb_table.py` fails when the committed file differs from `render()`.
"""

from __future__ import annotations

import argparse
import importlib.util
import struct
import sys
from pathlib import Path
from types import ModuleType

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE = REPO_ROOT / "python" / "uzpainter_facade" / "ocio_srgb.py"
TARGET = REPO_ROOT / "src" / "evaluator" / "ocio_srgb_table.inc"


def _bits(value: float) -> int:
    """The float32 bits of `value` rounded to float32."""
    return int(struct.unpack("<I", struct.pack("<f", value))[0])


def _exact_f32(value: float) -> int:
    """The bits of a value that must already be a float32."""
    bits = _bits(value)
    if struct.unpack("<f", struct.pack("<I", bits))[0] != value:
        raise ValueError(f"{value!r} is not a float32 value")
    return bits


def load_source() -> ModuleType:
    """`ocio_srgb.py` by path: it imports nothing, and the facade package needs the native one."""
    spec = importlib.util.spec_from_file_location("ocio_srgb", SOURCE)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def entries() -> dict[int, int]:
    """Component bits to working-value bits, built as the facade builds `_OCIO_SRGB`."""
    source = load_source()
    table: dict[int, int] = {}
    for c, working in enumerate(source.CODES):
        table[_bits(c / 255)] = _exact_f32(working)
    for x, working in source.RECORDED:
        table[_bits(x)] = _exact_f32(working)
    return table


def render() -> str:
    table = entries()
    lines = [
        "// Generated by tools/parity/ocio_srgb_table.py from",
        "// python/uzpainter_facade/ocio_srgb.py; do not edit. Painter's working value of an sRGB",
        "// uniform colour component under OCIO with its substance config (decision 202):",
        "// {float32 bits of the component, float32 bits of the working value},",
        f"// {len(table)} entries sorted by component bits.",
    ]
    lines += [f"{{0x{key:08x}u, 0x{table[key]:08x}u}}," for key in sorted(table)]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the .inc is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else None
        if current != text:
            print(f"{TARGET} is stale: run python tools/parity/ocio_srgb_table.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
