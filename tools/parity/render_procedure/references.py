def write_fixtures(directory: Path = FIXTURE_DIR) -> list[Path]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, data in committed_fixtures().items():
        path = directory / name
        path.write_bytes(data)
        written.append(path)
    return written


@dataclass(frozen=True)
class Perturbation:
    """One more channel in the material's fill: a uniform colour or an authored bitmap."""

    channel: str
    add_format: str | None = None  # Stack.add_channel format when the template lacks it
    bitmap: str | None = None  # committed fixture file name
    color: tuple[float, float, float] | None = None
    color_space: str | None = None


